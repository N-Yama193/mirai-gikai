import { AI_MODELS } from "@/lib/ai/models";

/** 議案AI要約生成で使用するモデル */
export const AGENDA_SUMMARY_MODEL = AI_MODELS.claude_sonnet_5;

export function buildAgendaSummaryPrompt(agendaBody: string): string {
  return `あなたは町議会の議事録要約アシスタントです。
以下の議案の提案理由・審議内容を要約してください。

【本文】
${agendaBody}

要約の方針:
- 全項目を漫然と均等に並べるのではなく、「この議案で一番重要なポイントは何か」を意識してメリハリをつけてください。
- conclusionは、読んだ人が数秒で「結局どんな議案か」がわかるように、最も重要な内容を一文で書いてください。「〜について改正する」だけの抽象的な言い回しで終わらせず、可能な限り具体的な内容（金額、対象範囲、変更点、住民への影響など）を含めてください。
- 本文が「提案理由は〜」のような短い一文しかない場合は、無理に情報を水増しせず、その内容を簡潔に伝えるだけで構いません。

本文に記載のない内容は推測せず、不明な場合は空文字にしてください。

以下のJSON形式で出力してください。

{
  "points": ["審議のポイント1", "審議のポイント2", ...],
  "conclusion": "議案の要旨・結論を100字程度で、具体的に"
}`;
}
